import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const code=readFileSync(path.join(root,'public/speedbox/network-tunnels.js'),'utf8');
const context=vm.createContext({window:{}});
vm.runInContext(code.replace('return {mount,label,actions};','return {mount,label,actions,parsePorts,validateMappings,portsText,endpoint};'),context);
const {parsePorts,validateMappings,portsText,endpoint,actions}=context.window.SpeedboxNetworkTunnels;
let checks=0;
const check=(value,message)=>{assert.ok(value,message);checks++;};
const reject=(fn,message)=>{assert.throws(fn,{name:'Error'},message);checks++;};
let maps=parsePorts('8444,443،۲۰۵۳ ٨٤٤٣');
check(JSON.stringify(maps)===JSON.stringify([{public_port:443,public_end:443,target_port:443,target_end:443,destinations:[]},{public_port:2053,public_end:2053,target_port:2053,target_end:2053,destinations:[]},{public_port:8443,public_end:8444,target_port:8443,target_end:8444,destinations:[]}]),'mixed Persian/Arabic/Latin input normalizes to ordered bounded mappings');
check(portsText(maps)==='443, 2053, 8443, 8444','range expands for editing without losing ports');
check(endpoint('2001:db8::1',8443,8445)==='[2001:db8::1]:8443–8445','IPv6 endpoint has brackets and full range');
for(const text of ['',',','0','65536','-1','1.2','443;whoami','1e3','443,443','443,0443'])reject(()=>parsePorts(text),'reject invalid port list '+text);
check(parsePorts('1,65535').length===2,'both port boundaries accepted');
const continuous=Array.from({length:256},(_,i)=>i+10000);maps=parsePorts(continuous.join(','));
check(maps.length===1&&maps[0].public_end===10255,'256 consecutive ports use one range');
reject(()=>parsePorts([...continuous,10256].join(',')),'more than 256 ports rejected');
check(parsePorts(Array.from({length:40},(_,i)=>10000+i*2).join(',')).length===40,'40 sparse paths accepted');
reject(()=>parsePorts(Array.from({length:41},(_,i)=>10000+i*2).join(',')),'41 sparse paths rejected by actual backend limit');
check(validateMappings([{public_port:10000,public_end:10002,target_port:443,target_end:445}])===undefined,'different equal-size port ranges accepted');
for(const maps of [[],[{public_port:0,target_port:1}],[{public_port:443,public_end:445,target_port:443,target_end:444}],[{public_port:1000,public_end:1256,target_port:1000,target_end:1256}],[{public_port:443,target_port:443},{public_port:443,target_port:8443}]])reject(()=>validateMappings(maps),'invalid range mapping rejected');
for(const engine of ['gost','gre']){
 const running=actions({engine,status:'connected',settings:{enabled:true}}).map(([name])=>name);
 const stopped=actions({engine,status:'stopped',settings:{enabled:false}}).map(([name])=>name);
 check(running.includes('stop')&&!running.includes('start'),'running '+engine+' exposes stop only');
 check(stopped.includes('start')&&!stopped.includes('stop'),'stopped '+engine+' exposes start only');
 check(!running.includes('add-peer')&&!running.includes('node')&&running.includes('logs'),'node and peer shortcuts removed; report available for '+engine);
 check(!running.includes('export')&&running.includes('diagnose')===(engine==='gre')&&running.includes('optimize')&&running.includes('engine-update'),'supported maintenance tools exposed for '+engine);
 check(running.includes('history')===(engine==='gre'),'history is a GRE operation');
 check(!running.includes('reset-quota'),'quota reset hidden with no quota');
}
check(actions({engine:'gre',settings:{quota_gb:1}}).some(([a])=>a==='reset-quota'),'GRE quota reset shown only for an enabled quota');
check(!actions({engine:'gost',settings:{quota_gb:1}}).some(([a])=>a==='reset-quota'),'GOST never exposes GRE quota reset');
console.log(`PASS: ${checks} tunnel form checks`);
