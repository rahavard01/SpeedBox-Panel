import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import vm from 'node:vm';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const context={window:{}};vm.runInNewContext(readFileSync(path.join(root,'public/speedbox/node-editor.js'),'utf8'),context);
const definition=JSON.parse(readFileSync(path.join(root,'agent/internal/model/kernel-capabilities.json'),'utf8'));
const resolve=(type,settings={})=>Array.from(context.window.SpeedboxNodeEditor.compatibleKernels(type,settings,definition).kernels);
let assertions=0;const check=(actual,expected)=>{assert.deepEqual(actual,expected);assertions++;};
for(const type of ['tuic','anytls','naive','mieru','socks','http'])check(resolve(type),['singbox']);
for(const type of ['vmess','vless','trojan','shadowsocks'])check(resolve(type),['singbox','xray']);
check(resolve('hysteria',{version:1}),['singbox']);check(resolve('hysteria',{version:2}),['singbox','xray']);
check(resolve('tuic',{version:4}),[]);check(resolve('tuic',{version:5}),['singbox']);
for(const network of ['xhttp','splithttp','kcp'])check(resolve('vless',{network}),['xray']);
check(resolve('vmess',{network:'tcp',network_settings:{header:{type:'http'}}}),['xray']);
check(resolve('vless',{network:'tcp',encryption:{enabled:true}}),['xray']);
check(resolve('vless',{network:'tcp',encryption:{enabled:false}}),['singbox','xray']);
check(resolve('shadowsocks',{cipher:'2022-blake3-chacha20-poly1305'}),['singbox']);
check(resolve('socks',{network:'xhttp'}),['singbox']);
check(Array.from(context.window.SpeedboxNodeEditor.compatibleKernels('vless',{},null).kernels),[]);
console.log(`PASS: ${assertions} node editor compatibility checks.`);
